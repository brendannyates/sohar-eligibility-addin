// Shared M helpers, inlined in each query so every source stays in its own query (the privacy firewall).
const HELPERS = `    // Text of a cell ('' for null); numbers without a trailing .0 (MRNs and Per Nbrs arrive as numbers sometimes).
    Txt = (v as any) as text => if v = null then "" else if Value.Is(v, type number) then (if Number.Round(v) = v then Number.ToText(v, "0") else Number.ToText(v, null, "en-US")) else Text.Trim(Text.From(v)),
    // M/D/YYYY, YYYY-MM-DD or a date -> "yyyy-MM-dd"; anything else as it was.
    IsoDay = (v as any) as text =>
        if v = null then ""
        else if Value.Is(v, type date) then Date.ToText(v, "yyyy-MM-dd")
        else if Value.Is(v, type datetime) then DateTime.ToText(v, "yyyy-MM-dd")
        else let s = Txt(v), p = Text.Split(Text.BeforeDelimiter(s, " "), "/") in
            if List.Count(p) = 3 and Text.Length(p{2}) = 4 then p{2} & "-" & Text.PadStart(p{0}, 2, "0") & "-" & Text.PadStart(p{1}, 2, "0")
            else if Text.Length(s) >= 10 and Text.Middle(s, 4, 1) = "-" then Text.Start(s, 10) else s,
    // Keep exactly Cols, in order: a column the source lacks comes in blank.
    Shape = (t as table, cols as list) as table =>
        let added = List.Accumulate(List.Difference(cols, Table.ColumnNames(t)), t, (acc, c) => Table.AddColumn(acc, c, each "", type text))
        in Table.SelectColumns(added, cols),
    // A CSV the rotation writes: UTF-8, quoted fields may span lines, a byte-order mark on the first header.
    ReadCsv = (bin as binary) as table =>
        let csv = Csv.Document(bin, [Delimiter = ",", Encoding = 65001, QuoteStyle = QuoteStyle.Csv]),
            promoted = Table.PromoteHeaders(csv, [PromoteAllScalars = true])
        in Table.TransformColumnNames(promoted, each Text.Trim(Text.Replace(_, "#(feff)", ""))),`;

